void mip_draw_char(int16_t x, int16_t y, char c, bool invert) {
    if (x <= -MIP_FONT_WIDTH || x >= MIP_WIDTH || y <= -MIP_FONT_HEIGHT || y >= MIP_HEIGHT) {
        return;
    }

    uint8_t glyph_idx = (uint8_t)c;
    if (glyph_idx < 0x20 || glyph_idx > 0x7E) {
        glyph_idx = 0x20; /* Default to space */
    }
    glyph_idx -= 0x20;

    const uint8_t *glyph_rows = FONT_8X12_TABLE[glyph_idx];
    mark_range_dirty(y, (int16_t)(y + MIP_FONT_HEIGHT - 1));

    for (int16_t row = 0; row < MIP_FONT_HEIGHT; row++) {
        int16_t cur_y = (int16_t)(y + row);
        if (cur_y < 0 || cur_y >= MIP_HEIGHT) continue;

        uint8_t pattern = glyph_rows[row];
        for (int16_t col = 0; col < MIP_FONT_WIDTH; col++) {
            int16_t cur_x = (int16_t)(x + col);
            if (cur_x < 0 || cur_x >= MIP_WIDTH) continue;

            bool pixel_active = (pattern & (0x80U >> col)) != 0;
            uint8_t final_color;

            if (invert) {
                final_color = pixel_active ? MIP_COLOR_WHITE : MIP_COLOR_BLACK;
            } else {
                final_color = pixel_active ? MIP_COLOR_BLACK : MIP_COLOR_WHITE;
            }

            uint16_t b_idx = (uint16_t)(cur_x >> 3);
            uint8_t mask = (uint8_t)(0x80U >> (cur_x & 7));

            if (final_color == MIP_COLOR_BLACK) {
                s_framebuffer[cur_y][b_idx] |= mask;
            } else {
                s_framebuffer[cur_y][b_idx] &= (uint8_t)~mask;
            }
        }
    }
}

void mip_draw_string(int16_t x, int16_t y, const char *str, bool invert) {
    if (!str) return;

    int16_t cur_x = x;
    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            y = (int16_t)(y + MIP_FONT_HEIGHT);
        } else {
            mip_draw_char(cur_x, y, *str, invert);
            cur_x = (int16_t)(cur_x + MIP_FONT_WIDTH);
        }
        str++;
    }
}
