/**
 * @file mip_display.c
 * @brief Zero-Heap Sharp 2.7" Memory-in-Pixel (LS027B7DH01A, 400x240) Display Driver,
 *        Dirty-Line DMA Engine & 2-Pixel Vector Graphics Runtime.
 */

#include "mip_display.h"
#include <string.h>
#include <stdlib.h>

/* -------------------------------------------------------------------------- */
/* Static BSS Allocation (Zero Heap Invariant)                                */
/* -------------------------------------------------------------------------- */
static uint8_t s_framebuffer[MIP_HEIGHT][MIP_ROW_BYTES]; /* 240 x 50 = 12,000 B */
static uint32_t s_dirty_lines[MIP_DIRTY_WORDS];          /* 8 x 32 = 256 bits   */
static uint8_t s_vcom_polarity = 0;                      /* 0 or 1              */

/* -------------------------------------------------------------------------- */
/* Internal Dirty Tagging Inlines                                             */
/* -------------------------------------------------------------------------- */
static inline void mark_line_dirty(uint16_t y) {
    if (y < MIP_HEIGHT) {
        s_dirty_lines[y >> 5] |= (1U << (y & 31));
    }
}

static inline void mark_range_dirty(int16_t y0, int16_t y1) {
    if (y0 > y1) { int16_t t = y0; y0 = y1; y1 = t; }
    if (y1 < 0 || y0 >= MIP_HEIGHT) return;
    if (y0 < 0) y0 = 0;
    if (y1 >= MIP_HEIGHT) y1 = MIP_HEIGHT - 1;

    for (int16_t y = y0; y <= y1; y++) {
        s_dirty_lines[y >> 5] |= (1U << (y & 31));
    }
}

/* -------------------------------------------------------------------------- */
/* Driver Lifecycle API                                                       */
/* -------------------------------------------------------------------------- */
void mip_display_init(void) {
    memset(s_framebuffer, 0x00, sizeof(s_framebuffer));
    memset(s_dirty_lines, 0x00, sizeof(s_dirty_lines));
    s_vcom_polarity = 0;
    mip_mark_all_dirty();
}

void mip_display_clear(uint8_t color) {
    uint8_t fill_byte = (color == MIP_COLOR_BLACK) ? 0xFF : 0x00;
    memset(s_framebuffer, fill_byte, sizeof(s_framebuffer));
    mip_mark_all_dirty();
}

void mip_blit_framebuffer(const uint8_t *src, size_t size) {
    if (!src || size != sizeof(s_framebuffer)) return;
    memcpy(s_framebuffer, src, sizeof(s_framebuffer));
    mip_mark_all_dirty();
}

void mip_display_vcom_toggle(void) {
    s_vcom_polarity ^= 1;
}

const uint8_t *mip_get_framebuffer(void) {
    return (const uint8_t *)s_framebuffer;
}

const uint32_t *mip_get_dirty_mask(void) {
    return s_dirty_lines;
}

void mip_mark_line_dirty(uint16_t y) {
    mark_line_dirty(y);
}

void mip_mark_all_dirty(void) {
    for (int i = 0; i < 7; i++) {
        s_dirty_lines[i] = 0xFFFFFFFFU;
    }
    /* 240 lines: words 0..6 cover lines 0..223 (7 * 32 = 224 lines).
       Word 7 covers lines 224..239 (16 lines -> 0x0000FFFF). */
    s_dirty_lines[7] = 0x0000FFFFU;
}

uint16_t mip_prepare_dma_stream(uint8_t *dma_buf, uint16_t *dma_len) {
    if (!dma_buf || !dma_len) return 0;

    uint16_t offset = 0;
    uint16_t dirty_count = 0;
    uint8_t cmd_byte = MIP_CMD_WRITE_LINE | (s_vcom_polarity ? MIP_CMD_VCOM_MASK : 0x00);

    for (uint16_t y = 0; y < MIP_HEIGHT; y++) {
        uint32_t word = s_dirty_lines[y >> 5];
        if (word & (1U << (y & 31))) {
            uint8_t *pkt = &dma_buf[offset];

            pkt[0] = cmd_byte;
            pkt[1] = (uint8_t)(y + 1); /* Sharp Memory LCD line addresses are 1-based (1..240) */
            memcpy(&pkt[2], s_framebuffer[y], MIP_ROW_BYTES);
            pkt[52] = 0x00; /* Dummy byte 1 */
            pkt[53] = 0x00; /* Dummy byte 2 */

            offset = (uint16_t)(offset + MIP_DMA_LINE_PACKET_SIZE);
            dirty_count++;
        }
    }

    /* Clear dirty mask following DMA preparation */
    memset(s_dirty_lines, 0x00, sizeof(s_dirty_lines));

    *dma_len = offset;
    return dirty_count;
}

/* -------------------------------------------------------------------------- */
/* Vector Graphics Primitives                                                 */
/* -------------------------------------------------------------------------- */
void mip_draw_pixel(int16_t x, int16_t y, uint8_t color) {
    if (x < 0 || x >= MIP_WIDTH || y < 0 || y >= MIP_HEIGHT) {
        return;
    }

    uint16_t byte_idx = (uint16_t)(x >> 3);
    uint8_t bit_mask = (uint8_t)(0x80U >> (x & 7));

    if (color == MIP_COLOR_BLACK) {
        s_framebuffer[y][byte_idx] |= bit_mask;
    } else {
        s_framebuffer[y][byte_idx] &= (uint8_t)~bit_mask;
    }

    mark_line_dirty((uint16_t)y);
}

void mip_draw_hline(int16_t x0, int16_t x1, int16_t y, uint8_t color) {
    if (y < 0 || y >= MIP_HEIGHT) return;
    if (x0 > x1) { int16_t t = x0; x0 = x1; x1 = t; }
    if (x1 < 0 || x0 >= MIP_WIDTH) return;

    if (x0 < 0) x0 = 0;
    if (x1 >= MIP_WIDTH) x1 = MIP_WIDTH - 1;

    int16_t b_start = x0 >> 3;
    int16_t b_end = x1 >> 3;

    if (b_start == b_end) {
        /* Single byte modification */
        uint8_t mask = 0;
        for (int16_t x = x0; x <= x1; x++) {
            mask |= (uint8_t)(0x80U >> (x & 7));
        }
        if (color == MIP_COLOR_BLACK) {
            s_framebuffer[y][b_start] |= mask;
        } else {
            s_framebuffer[y][b_start] &= (uint8_t)~mask;
        }
    } else {
        /* Start partial byte */
        uint8_t start_mask = (uint8_t)(0xFFU >> (x0 & 7));
        if (color == MIP_COLOR_BLACK) {
            s_framebuffer[y][b_start] |= start_mask;
        } else {
            s_framebuffer[y][b_start] &= (uint8_t)~start_mask;
        }

        /* Middle full bytes */
        if (b_end > b_start + 1) {
            uint8_t fill_val = (color == MIP_COLOR_BLACK) ? 0xFF : 0x00;
            memset(&s_framebuffer[y][b_start + 1], fill_val, (size_t)(b_end - b_start - 1));
        }

        /* End partial byte */
        uint8_t end_mask = (uint8_t)~(0xFFU >> ((x1 & 7) + 1));
        if (color == MIP_COLOR_BLACK) {
            s_framebuffer[y][b_end] |= end_mask;
        } else {
            s_framebuffer[y][b_end] &= (uint8_t)~end_mask;
        }
    }

    mark_line_dirty((uint16_t)y);
}

void mip_draw_vline(int16_t x, int16_t y0, int16_t y1, uint8_t color) {
    if (x < 0 || x >= MIP_WIDTH) return;
    if (y0 > y1) { int16_t t = y0; y0 = y1; y1 = t; }
    if (y1 < 0 || y0 >= MIP_HEIGHT) return;

    if (y0 < 0) y0 = 0;
    if (y1 >= MIP_HEIGHT) y1 = MIP_HEIGHT - 1;

    uint16_t byte_idx = (uint16_t)(x >> 3);
    uint8_t bit_mask = (uint8_t)(0x80U >> (x & 7));

    if (color == MIP_COLOR_BLACK) {
        for (int16_t y = y0; y <= y1; y++) {
            s_framebuffer[y][byte_idx] |= bit_mask;
            mark_line_dirty((uint16_t)y);
        }
    } else {
        uint8_t not_mask = (uint8_t)~bit_mask;
        for (int16_t y = y0; y <= y1; y++) {
            s_framebuffer[y][byte_idx] &= not_mask;
            mark_line_dirty((uint16_t)y);
        }
    }
}

void mip_draw_rect(int16_t x, int16_t y, int16_t w, int16_t h, bool fill, uint8_t color) {
    if (w <= 0 || h <= 0) return;

    if (fill) {
        for (int16_t cur_y = y; cur_y < y + h; cur_y++) {
            mip_draw_hline(x, (int16_t)(x + w - 1), cur_y, color);
        }
    } else {
        mip_draw_hline(x, (int16_t)(x + w - 1), y, color);
        mip_draw_hline(x, (int16_t)(x + w - 1), (int16_t)(y + h - 1), color);
        mip_draw_vline(x, y, (int16_t)(y + h - 1), color);
        mip_draw_vline((int16_t)(x + w - 1), y, (int16_t)(y + h - 1), color);
    }
}

/* Cohen-Sutherland Clipper */
#define CS_INSIDE 0
#define CS_LEFT   1
#define CS_RIGHT  2
#define CS_BOTTOM 4
#define CS_TOP    8

static inline int cs_compute_outcode(int16_t x, int16_t y, int16_t xmin, int16_t ymin, int16_t xmax, int16_t ymax) {
    int code = CS_INSIDE;
    if (x < xmin) code |= CS_LEFT;
    else if (x > xmax) code |= CS_RIGHT;
    if (y < ymin) code |= CS_TOP;
    else if (y > ymax) code |= CS_BOTTOM;
    return code;
}

static bool cs_clip_line(int16_t *x0, int16_t *y0, int16_t *x1, int16_t *y1,
                         int16_t xmin, int16_t ymin, int16_t xmax, int16_t ymax) {
    int code0 = cs_compute_outcode(*x0, *y0, xmin, ymin, xmax, ymax);
    int code1 = cs_compute_outcode(*x1, *y1, xmin, ymin, xmax, ymax);

    while (1) {
        if (!(code0 | code1)) {
            return true;
        } else if (code0 & code1) {
            return false;
        } else {
            int code_out = code0 ? code0 : code1;
            int32_t x = 0, y = 0;
            int32_t x0_32 = *x0, y0_32 = *y0;
            int32_t x1_32 = *x1, y1_32 = *y1;

            if (code_out & CS_TOP) {
                x = (y1_32 != y0_32) ? (x0_32 + (x1_32 - x0_32) * (ymin - y0_32) / (y1_32 - y0_32)) : x0_32;
                y = ymin;
            } else if (code_out & CS_BOTTOM) {
                x = (y1_32 != y0_32) ? (x0_32 + (x1_32 - x0_32) * (ymax - y0_32) / (y1_32 - y0_32)) : x0_32;
                y = ymax;
            } else if (code_out & CS_RIGHT) {
                y = (x1_32 != y0_32) ? (y0_32 + (y1_32 - y0_32) * (xmax - x0_32) / (x1_32 - x0_32)) : y0_32;
                x = xmax;
            } else if (code_out & CS_LEFT) {
                y = (x1_32 != y0_32) ? (y0_32 + (y1_32 - y0_32) * (xmin - x0_32) / (x1_32 - x0_32)) : y0_32;
                x = xmin;
            }

            if (code_out == code0) {
                *x0 = (int16_t)x;
                *y0 = (int16_t)y;
                code0 = cs_compute_outcode(*x0, *y0, xmin, ymin, xmax, ymax);
            } else {
                *x1 = (int16_t)x;
                *y1 = (int16_t)y;
                code1 = cs_compute_outcode(*x1, *y1, xmin, ymin, xmax, ymax);
            }
        }
    }
}

void mip_draw_line_thick(int16_t x0, int16_t y0, int16_t x1, int16_t y1,
                         uint8_t thickness, uint8_t color) {
    if (!cs_clip_line(&x0, &y0, &x1, &y1, 0, 0, MIP_WIDTH - 1, MIP_HEIGHT - 1)) {
        return;
    }

    mark_range_dirty(y0, (int16_t)(y1 + (thickness > 1 ? 1 : 0)));

    int16_t dx = (int16_t)abs(x1 - x0);
    int16_t dy = (int16_t)abs(y1 - y0);
    int16_t sx = (x0 < x1) ? 1 : -1;
    int16_t sy = (y0 < y1) ? 1 : -1;
    int16_t err = (int16_t)(dx - dy);

    while (1) {
        /* Plot base pixel */
        mip_draw_pixel(x0, y0, color);

        /* 2x2 optical brush expansion */
        if (thickness >= 2) {
            if (x0 + 1 < MIP_WIDTH) mip_draw_pixel((int16_t)(x0 + 1), y0, color);
            if (y0 + 1 < MIP_HEIGHT) mip_draw_pixel(x0, (int16_t)(y0 + 1), color);
            if (x0 + 1 < MIP_WIDTH && y0 + 1 < MIP_HEIGHT) {
                mip_draw_pixel((int16_t)(x0 + 1), (int16_t)(y0 + 1), color);
            }
        }

        if (x0 == x1 && y0 == y1) break;
        int32_t e2 = 2 * err;
        if (e2 > -dy) {
            err = (int16_t)(err - dy);
            x0 = (int16_t)(x0 + sx);
        }
        if (e2 < dx) {
            err = (int16_t)(err + dx);
            y0 = (int16_t)(y0 + sy);
        }
    }
}

